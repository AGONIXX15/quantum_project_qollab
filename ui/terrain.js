/*
  Real-world terrain data for the 3D map: decoded DEM, one shared lat/lon -> scene
  projection, and the draped colour texture (NASA Blue Marble, with Colombia
  highlighted and its neighbours dimmed).

  Data lives in ui/data/*.js (generated by tools/bake_terrain.py) because Qollab can
  only import .js files; nothing is fetched at runtime.

  Projection: project()/unproject() from colombia-geo.js, identical to quantum/geo.py
  (x east, z south). Multiply by WORLD to get scene units.
*/

import { TERRAIN } from "./data/terrain.js";
import { EARTH_COLOR } from "./data/earth_color.js";
import { BORDERS } from "./data/borders.js";
import { project, unproject } from "./colombia-geo.js";

export const WORLD = 6;
export const BBOX = TERRAIN.bbox;
export { BORDERS };

// Vertical exaggeration (scene units per km). Land is exaggerated enough to read the three
// cordilleras and the Sierra Nevada; the sea floor is flattened so trenches do not dominate.
export const LAND_PER_KM = 0.2;
export const SEA_PER_KM = 0.05;

export const toScene = (lat, lon) => {
  const p = project(lat, lon);
  return { x: p.x * WORLD, z: p.z * WORLD };
};
export const fromScene = (x, z) => unproject(x / WORLD, z / WORLD);

export const elevToUnits = (m) => (m >= 0 ? (m / 1000) * LAND_PER_KM : (m / 1000) * SEA_PER_KM);

// ---- DEM decode ---------------------------------------------------------------
function decodeDem() {
  const bin = atob(TERRAIN.data);
  const n = TERRAIN.width * TERRAIN.height;
  const out = new Float32Array(n);
  const span = TERRAIN.maxElev - TERRAIN.minElev;
  for (let i = 0; i < n; i++) {
    const v = bin.charCodeAt(2 * i) | (bin.charCodeAt(2 * i + 1) << 8); // little endian
    out[i] = TERRAIN.minElev + (v / 65535) * span;
  }
  return out;
}
export const DEM = decodeDem();
export const DEM_W = TERRAIN.width;
export const DEM_H = TERRAIN.height;
export const LON_SPAN = BBOX.east - BBOX.west;
export const LAT_SPAN = BBOX.north - BBOX.south;

// Bilinear elevation in metres at lat/lon (cell centres), clamped to the grid.
export function elevationM(lat, lon) {
  const fx = Math.min(DEM_W - 1.001, Math.max(0, ((lon - BBOX.west) / LON_SPAN) * DEM_W - 0.5));
  const fy = Math.min(DEM_H - 1.001, Math.max(0, ((BBOX.north - lat) / LAT_SPAN) * DEM_H - 0.5));
  const x0 = Math.floor(fx), y0 = Math.floor(fy);
  const ax = fx - x0, ay = fy - y0;
  const i = y0 * DEM_W + x0;
  return (
    DEM[i] * (1 - ax) * (1 - ay) + DEM[i + 1] * ax * (1 - ay) +
    DEM[i + DEM_W] * (1 - ax) * ay + DEM[i + DEM_W + 1] * ax * ay
  );
}

// Terrain surface height in scene units at scene (x, z).
export function heightAt(x, z) {
  const { lat, lon } = fromScene(x, z);
  return elevToUnits(elevationM(lat, lon));
}

// Great-circle distance in km between two lat/lon points.
export function haversineKm(lat1, lon1, lat2, lon2) {
  const r = Math.PI / 180;
  const dphi = (lat2 - lat1) * r, dl = (lon2 - lon1) * r;
  const h = Math.sin(dphi / 2) ** 2 + Math.cos(lat1 * r) * Math.cos(lat2 * r) * Math.sin(dl / 2) ** 2;
  return 2 * 6371.0088 * Math.asin(Math.sqrt(h));
}

// ---- Colour texture ------------------------------------------------------------
const BG = [18, 26, 43];
const RAMP = [ // metres, r, g, b : fallback when the Blue Marble image cannot be decoded
  [-4500, 8, 28, 56], [-2000, 12, 48, 84], [-200, 38, 100, 130], [0, 61, 122, 70], [300, 92, 138, 74],
  [1200, 138, 122, 85], [2500, 150, 132, 100], [3800, 170, 164, 150], [4800, 245, 247, 252],
];
function rampColor(m) {
  if (m <= RAMP[0][0]) return RAMP[0].slice(1);
  for (let i = 1; i < RAMP.length; i++) {
    if (m <= RAMP[i][0]) {
      const a = RAMP[i - 1], b = RAMP[i], f = (m - a[0]) / (b[0] - a[0]);
      return [a[1] + (b[1] - a[1]) * f, a[2] + (b[2] - a[2]) * f, a[3] + (b[3] - a[3]) * f];
    }
  }
  return RAMP[RAMP.length - 1].slice(1);
}

const smooth = (a, b, x) => {
  const t = Math.min(1, Math.max(0, (x - a) / (b - a)));
  return t * t * (3 - 2 * t);
};

function tracePath(ctx, ring, cw, ch) {
  ring.forEach(([lon, lat], i) => {
    const x = ((lon - BBOX.west) / LON_SPAN) * cw;
    const y = ((BBOX.north - lat) / LAT_SPAN) * ch;
    if (i === 0) ctx.moveTo(x, y);
    else ctx.lineTo(x, y);
  });
}

/**
 * Paint the map texture into `canvas`: Blue Marble (or elevation ramp when `img` is null),
 * neighbours desaturated and dimmed, edge vignette, glowing Colombia border.
 */
export function paintEarth(canvas, img) {
  const cw = canvas.width, ch = canvas.height;
  const ctx = canvas.getContext("2d", { willReadFrequently: true });
  if (img) {
    ctx.drawImage(img, 0, 0, cw, ch);
  } else {
    const im = ctx.createImageData(cw, ch);
    for (let y = 0; y < ch; y++) {
      for (let x = 0; x < cw; x++) {
        const lon = BBOX.west + ((x + 0.5) / cw) * LON_SPAN;
        const lat = BBOX.north - ((y + 0.5) / ch) * LAT_SPAN;
        const c = rampColor(elevationM(lat, lon));
        const o = (y * cw + x) * 4;
        im.data[o] = c[0]; im.data[o + 1] = c[1]; im.data[o + 2] = c[2]; im.data[o + 3] = 255;
      }
    }
    ctx.putImageData(im, 0, 0);
  }

  // Mask of Colombia (white inside).
  const mask = document.createElement("canvas");
  mask.width = cw; mask.height = ch;
  const mctx = mask.getContext("2d", { willReadFrequently: true });
  mctx.fillStyle = "#000"; mctx.fillRect(0, 0, cw, ch);
  mctx.fillStyle = "#fff";
  for (const ring of BORDERS.colombia) { mctx.beginPath(); tracePath(mctx, ring, cw, ch); mctx.closePath(); mctx.fill(); }
  const md = mctx.getImageData(0, 0, cw, ch).data;

  const data = ctx.getImageData(0, 0, cw, ch);
  const d = data.data;
  for (let y = 0; y < ch; y++) {
    const v = y / ch;
    for (let x = 0; x < cw; x++) {
      const o = (y * cw + x) * 4;
      const m = md[o] / 255;
      let r = d[o], g = d[o + 1], b = d[o + 2];
      if (m < 1) { // neighbours: desaturate + dim
        const lum = 0.3 * r + 0.59 * g + 0.11 * b;
        const k = 0.6 + 0.4 * m;
        const dim = 0.86 + 0.14 * m;
        r = (lum + (r - lum) * k) * dim; g = (lum + (g - lum) * k) * dim; b = (lum + (b - lum) * k) * dim;
      }
      const gain = 1.1 + 0.2 * m; // Blue Marble is dark under tropical forest
      r *= gain; g *= gain; b *= gain;
      const u = x / cw;
      const f = smooth(0, 0.07, Math.min(u, 1 - u, v, 1 - v));
      d[o] = BG[0] + (r - BG[0]) * f;
      d[o + 1] = BG[1] + (g - BG[1]) * f;
      d[o + 2] = BG[2] + (b - BG[2]) * f;
    }
  }
  ctx.putImageData(data, 0, 0);

  // Neighbour borders (faint) and Colombia border (glowing).
  ctx.lineJoin = "round";
  ctx.strokeStyle = "rgba(255,255,255,0.28)";
  ctx.lineWidth = 1;
  for (const ring of BORDERS.neighbours) { ctx.beginPath(); tracePath(ctx, ring, cw, ch); ctx.stroke(); }
  ctx.save();
  ctx.shadowColor = "rgba(90,255,225,0.95)";
  ctx.shadowBlur = 8;
  ctx.strokeStyle = "rgba(170,255,238,0.95)";
  ctx.lineWidth = 2;
  for (const ring of BORDERS.colombia) { ctx.beginPath(); tracePath(ctx, ring, cw, ch); ctx.closePath(); ctx.stroke(); }
  ctx.restore();
}

// Decodes the Blue Marble data URL; resolves null (never rejects) when it fails.
export function loadEarthImage() {
  return new Promise((resolve) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = () => resolve(null);
    img.src = EARTH_COLOR;
  });
}

export const EARTH_SIZE = { w: 1024, h: Math.round((1024 * LAT_SPAN) / LON_SPAN) };
