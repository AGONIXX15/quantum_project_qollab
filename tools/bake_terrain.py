#!/usr/bin/env python3
"""Bake the map data used by ui/scene.js (run offline-reproducibly, output is committed).

Writes into ui/data/:
  terrain.js      elevation grid (AWS Terrain Tiles / terrarium, ocean bathymetry included)
  earth_color.js  NASA Blue Marble crop as a JPEG data: URL
  borders.js      Colombia + neighbour borders (Natural Earth 1:50m, public domain)

Usage:  python3 tools/bake_terrain.py [--cache DIR]
Needs Pillow + numpy (uv env has numpy; system python has Pillow). Downloads are cached in
--cache and treated as data only. Data credits: see README "Prior work & AI disclosure".
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import math
import os
import urllib.request

import numpy as np
from PIL import Image

BBOX = {"west": -92.0, "east": -58.0, "south": -8.0, "north": 16.0}
ZOOM = 6
GRID_W = 512
COLOR_W = 1024
MIN_ELEV_CLAMP = -4500.0  # deeper trench floor is clamped (precision, no visual use)
TILE_URL = "https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{z}/{x}/{y}.png"
BM_URL = "https://eoimages.gsfc.nasa.gov/images/imagerecords/74000/74092/world.200407.3x5400x2700.jpg"
NE_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ui", "data")


def fetch(url: str, path: str) -> str:
    if not os.path.exists(path):
        req = urllib.request.Request(url, headers={"User-Agent": "entangle-the-andes-bake/1.0"})
        with urllib.request.urlopen(req, timeout=120) as r, open(path, "wb") as f:
            f.write(r.read())
    return path


def lon2x(lon: float, z: int) -> float:
    return (lon + 180.0) / 360.0 * (2**z)


def lat2y(lat: float, z: int) -> float:
    r = math.radians(lat)
    return (1 - math.asinh(math.tan(r)) / math.pi) / 2 * (2**z)


def bake_terrain(cache: str) -> tuple[np.ndarray, float, float]:
    x0, x1 = int(lon2x(BBOX["west"], ZOOM)), int(lon2x(BBOX["east"], ZOOM))
    y0, y1 = int(lat2y(BBOX["north"], ZOOM)), int(lat2y(BBOX["south"], ZOOM))
    w, h = (x1 - x0 + 1) * 256, (y1 - y0 + 1) * 256
    big = np.zeros((h, w), dtype=np.float32)
    for ty in range(y0, y1 + 1):
        for tx in range(x0, x1 + 1):
            p = fetch(TILE_URL.format(z=ZOOM, x=tx, y=ty), os.path.join(cache, f"t{ZOOM}_{tx}_{ty}.png"))
            a = np.asarray(Image.open(p).convert("RGB"), dtype=np.float32)
            big[(ty - y0) * 256:(ty - y0 + 1) * 256, (tx - x0) * 256:(tx - x0 + 1) * 256] = (
                a[..., 0] * 256 + a[..., 1] + a[..., 2] / 256 - 32768)
    # Reproject Mercator -> equirectangular grid (bilinear), area-average first via 2x oversampling.
    gh = round(GRID_W * (BBOX["north"] - BBOX["south"]) / (BBOX["east"] - BBOX["west"]))
    lons = BBOX["west"] + (np.arange(GRID_W) + 0.5) / GRID_W * (BBOX["east"] - BBOX["west"])
    lats = BBOX["north"] - (np.arange(gh) + 0.5) / gh * (BBOX["north"] - BBOX["south"])
    px = (np.array([lon2x(v, ZOOM) for v in lons]) - x0) * 256 - 0.5
    py = (np.array([lat2y(v, ZOOM) for v in lats]) - y0) * 256 - 0.5
    # Box-blur the source to ~grid resolution so peaks are not aliased.
    k = max(1, int(round(big.shape[1] / GRID_W)))
    pad = np.pad(big, k // 2, mode="edge")
    cs = pad.cumsum(0).cumsum(1)
    cs = np.pad(cs, ((1, 0), (1, 0)))
    sm = (cs[k:, k:][:h, :w] - cs[:-k, k:][:h, :w] - cs[k:, :-k][:h, :w] + cs[:-k, :-k][:h, :w]) / (k * k)
    ix, iy = np.clip(px, 0, w - 1.001), np.clip(py, 0, h - 1.001)
    fx, fy = ix - np.floor(ix), (iy - np.floor(iy))[:, None]
    ix0, iy0 = np.floor(ix).astype(int), np.floor(iy).astype(int)
    fx = fx[None, :]
    g = (sm[iy0][:, ix0] * (1 - fx) * (1 - fy) + sm[iy0][:, ix0 + 1] * fx * (1 - fy)
         + sm[iy0 + 1][:, ix0] * (1 - fx) * fy + sm[iy0 + 1][:, ix0 + 1] * fx * fy)
    g = np.maximum(g, MIN_ELEV_CLAMP)
    return g, float(g.min()), float(g.max())


def write_terrain(g: np.ndarray, lo: float, hi: float) -> int:
    q = np.round((g - lo) / (hi - lo) * 65535).astype("<u2")
    b64 = base64.b64encode(q.tobytes()).decode()
    txt = (
        "// GENERATED by tools/bake_terrain.py - do not edit. Elevation: AWS Terrain Tiles (Mapzen; SRTM,\n"
        "// GMTED2010, ETOPO1...), https://github.com/tilezen/joerd/blob/master/docs/attribution.md\n"
        "// data = base64 of little-endian Uint16, row-major from the NW corner; metres = minElev + v/65535*(maxElev-minElev)\n"
        f"export const TERRAIN = {{\n  bbox: {json.dumps(BBOX)},\n  width: {g.shape[1]},\n  height: {g.shape[0]},\n"
        f"  minElev: {lo:.1f},\n  maxElev: {hi:.1f},\n  data: \"{b64}\",\n}};\n")
    with open(os.path.join(OUT, "terrain.js"), "w") as f:
        f.write(txt)
    return len(txt)


def write_color(cache: str) -> int:
    im = Image.open(fetch(BM_URL, os.path.join(cache, "bm.jpg"))).convert("RGB")
    W, H = im.size
    box = ((BBOX["west"] + 180) / 360 * W, (90 - BBOX["north"]) / 180 * H,
           (BBOX["east"] + 180) / 360 * W, (90 - BBOX["south"]) / 180 * H)
    ch = round(COLOR_W * (BBOX["north"] - BBOX["south"]) / (BBOX["east"] - BBOX["west"]))
    out = im.resize((COLOR_W, ch), Image.BICUBIC, box=box)
    buf = io.BytesIO()
    out.save(buf, "JPEG", quality=80, optimize=True)
    url = "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()
    txt = ("// GENERATED by tools/bake_terrain.py - do not edit. NASA Blue Marble (public domain, NASA Earth\n"
           "// Observatory), cropped to the terrain bbox.\n"
           f"export const EARTH_COLOR = \"{url}\";\n")
    with open(os.path.join(OUT, "earth_color.js"), "w") as f:
        f.write(txt)
    return len(txt)


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-12
    best, bi = 0.0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / n
        if d > best:
            best, bi = d, i
    if best <= eps:
        return [pts[0], pts[-1]]
    return rdp(pts[:bi + 1], eps)[:-1] + rdp(pts[bi:], eps)


def write_borders(cache: str) -> int:
    with open(fetch(NE_URL, os.path.join(cache, "ne50.geojson"))) as f:
        feats = json.load(f)["features"]
    want = {"COL": "colombia", "PAN": "n", "VEN": "n", "ECU": "n", "PER": "n", "BRA": "n", "GUY": "n",
            "CRI": "n", "NIC": "n", "JAM": "n", "HTI": "n", "DOM": "n", "CUB": "n", "HND": "n", "SUR": "n", "TTO": "n"}
    res: dict[str, list] = {"colombia": [], "neighbours": []}
    for ft in feats:
        p = ft["properties"]
        iso = p.get("ADM0_A3") or p.get("ISO_A3")
        if iso not in want:
            continue
        geom = ft["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            ring = [(x, y) for x, y in poly[0]]
            if not any(BBOX["west"] <= x <= BBOX["east"] and BBOX["south"] <= y <= BBOX["north"] for x, y in ring):
                continue
            eps = 0.02 if iso == "COL" else 0.05
            m = len(ring) // 2  # closed ring: simplify two halves (first == last point)
            s = rdp(ring[:m + 1], eps)[:-1] + rdp(ring[m:], eps)
            if iso == "COL" and len(ring) < 12:
                continue
            res["colombia" if iso == "COL" else "neighbours"].append([[round(x, 3), round(y, 3)] for x, y in s])
    txt = ("// GENERATED by tools/bake_terrain.py - do not edit. Natural Earth 1:50m admin-0 (public domain),\n"
           "// simplified. Rings of [lon, lat]. Drawn only, not authoritative cartography.\n"
           f"export const BORDERS = {json.dumps(res, separators=(',', ':'))};\n")
    with open(os.path.join(OUT, "borders.js"), "w") as f:
        f.write(txt)
    return len(txt)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".cache_bake"))
    a = ap.parse_args()
    os.makedirs(a.cache, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    g, lo, hi = bake_terrain(a.cache)
    print("terrain.js", write_terrain(g, lo, hi), "bytes", g.shape, lo, hi)
    print("earth_color.js", write_color(a.cache), "bytes")
    print("borders.js", write_borders(a.cache), "bytes")


if __name__ == "__main__":
    main()
