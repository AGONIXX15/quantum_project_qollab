"""Link budget for a Bogota-Medellin-Cali quantum network, from the project's own models.

Usage (repo root):  uv run python tools/network_budget.py
Prints a Markdown table and writes docs/img/network_budget.png. No circuits are run: only
quantum/geo.py (length, loss, pair rate), quantum/swap.py (swap_bell_diag), quantum/noise.py
(Werner -> Bell-diagonal) and quantum/analysis.py (key rates).

Assumptions (all stated, none measured):
    A1  Source of 1e9 pair attempts/s at one end of every segment (optimistic).
    A2  One photon crosses a segment, eta = 10^(-0.02 L) (geo.transmissivity).
    A3  Repeaters: ideal memories and deterministic swaps; the rate is limited by one
        segment, rate ~ SOURCE_RATE * eta_segment (same as geo.reroute_eta "ideal_memory").
    A4  Fibre length = great circle x 1.3 (geo.FIBER_ROUTE_FACTOR), not surveyed.
    A5  Segments are equal and every segment is Werner(F_seg); no memory decoherence,
        no gate noise, no detector losses/dark counts, no purification.
    A6  Key rate: asymptotic Shor-Preskill 1 - 2h(Q), Q = 2(1-F)/3 in each basis, times
        1/2 for BB84 sifting (same convention as quantum/rescue.py).
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from quantum import analysis as an  # noqa: E402
from quantum import geo  # noqa: E402
from quantum.noise import werner_probs  # noqa: E402
from quantum.swap import swap_bell_diag  # noqa: E402

SOURCE_RATE = 1e9
F_KEY = 0.835          # Q < 0.110 <=> F > 0.835 (Shor-Preskill)
F_CHSH = 0.7803        # S = 2*sqrt(2)*(4F-1)/3 > 2
F_SEGS = (0.99, 0.95)
N_MAX = 30
ROUTES = {
    "BOG-MED": ("BOG", "MED"), "MED-CAL": ("MED", "CAL"), "BOG-CAL": ("BOG", "CAL"),
    "BOG-MED-CAL": ("BOG", "MED", "CAL"),
}

BLUE, VERM, GREEN, ORANGE, BLACK = "#0072B2", "#D55E00", "#009E73", "#E69F00", "#000000"
FOOTER = "Model: quantum/geo.py + quantum/swap.py · generated by tools/network_budget.py"
OUT = ROOT / "docs" / "img" / "network_budget.png"


def route_length_km(cities: tuple[str, ...]) -> float:
    """Fibre length of a route through the given cities (sum of link lengths)."""
    return sum(geo.link_length_km(a, b) for a, b in zip(cities, cities[1:]))


def e2e_fidelity(F_seg: float, n: int) -> float:
    """End-to-end fidelity of n equal Werner(F_seg) segments (fold of swap_bell_diag)."""
    p = werner_probs(F_seg)
    for _ in range(n - 1):
        p = swap_bell_diag(p, werner_probs(F_seg))
    return float(p[0])


def closed_form(F_seg: float, n: int) -> float:
    """F_n = 1/4 + 3/4 ((4F-1)/3)^n."""
    return 0.25 + 0.75 * ((4 * F_seg - 1) / 3) ** n


def qber(F: float) -> float:
    """QBER of a Werner(F) state in each basis."""
    return 2 * (1 - F) / 3


def key_per_pair(F: float) -> float:
    """Asymptotic key bits per delivered pair (Shor-Preskill, x1/2 sifting)."""
    q = qber(F)
    return 0.5 * an.key_rate_per_basis(q, q)


def pair_rate(length_km: float, n: int) -> float:
    """Pairs/s with n equal segments, ideal memories: source rate x eta of one segment."""
    return geo.expected_pair_rate(SOURCE_RATE, length_km / n)


def can_chsh(F: float) -> bool:
    return F > F_CHSH


def can_key(F: float) -> bool:
    return F > F_KEY


def max_segments_for_key(F_seg: float, limit: int = 200) -> int:
    """Largest n with end-to-end F > 0.835 (0 if even n=1 fails). F falls with n."""
    best = 0
    for n in range(1, limit + 1):
        if can_key(e2e_fidelity(F_seg, n)):
            best = n
        else:
            break
    return best


def _fmt(x: float) -> str:
    return f"{x:.1e}" if x < 0.1 or x >= 1e4 else f"{x:.2f}"


def build_tables() -> str:
    lines = ["| Route | Fibre km | Case | n | Seg. km | eta/segment | Pairs/s | F_e2e | CHSH>2 | Key | Key bits/pair | Key bits/s |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, cities in ROUTES.items():
        L = route_length_km(cities)
        rows = [("direct (ideal F=1)", 1, 1.0)]
        for Fs in F_SEGS:
            nmax = max_segments_for_key(Fs)
            rows.append((f"F_seg={Fs}, n at key limit", nmax, Fs))
        for Fs in F_SEGS:  # smallest n giving >= 1 pair/s is informative
            n1 = next((n for n in range(1, 400) if pair_rate(L, n) >= 1.0), None)
            if n1 is not None and 1 < n1 <= max_segments_for_key(Fs):
                rows.append((f"F_seg={Fs}, n for >=1 pair/s", n1, Fs))
        for case, n, Fs in rows:
            F = e2e_fidelity(Fs, n) if Fs < 1 else 1.0
            r = pair_rate(L, n)
            k = key_per_pair(F)
            lines.append(
                f"| {name} | {L:.0f} | {case} | {n} | {L / n:.0f} | {geo.transmissivity(L / n):.2e} | "
                f"{_fmt(r)} | {F:.4f} | {'yes' if can_chsh(F) else 'no'} | {'yes' if can_key(F) else 'no'} | "
                f"{k:.3f} | {_fmt(r * k)} |")
    return "\n".join(lines)


def build_sweep(route: str = "BOG-MED-CAL") -> str:
    L = route_length_km(ROUTES[route])
    lines = [f"| {route} ({L:.0f} km) n | Seg. km | Pairs/s | F_e2e (0.99) | F_e2e (0.95) |", "|---|---|---|---|---|"]
    for n in (1, 2, 3, 4, 5, 8, 15, 30):
        lines.append(f"| {n} | {L / n:.0f} | {_fmt(pair_rate(L, n))} | "
                     f"{e2e_fidelity(0.99, n):.4f} | {e2e_fidelity(0.95, n):.4f} |")
    return "\n".join(lines)


def make_figure(route: str = "BOG-MED-CAL") -> None:
    L = route_length_km(ROUTES[route])
    ns = list(range(1, N_MAX + 1))
    plt.rcParams.update({
        "font.size": 10.5, "axes.titlesize": 11.5, "axes.titleweight": "bold",
        "axes.spines.top": False, "axes.spines.right": False, "figure.facecolor": "white",
        "axes.facecolor": "white", "savefig.facecolor": "white", "axes.grid": True,
        "grid.color": "#dddddd", "grid.linewidth": 0.6, "axes.axisbelow": True})
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4.4))
    a1.plot(ns, [math.log10(pair_rate(L, n)) for n in ns], "o-", color=BLUE, ms=4, label="pair rate (ideal memories)")
    a1.axhline(0, color=BLACK, ls=":", lw=1)
    a1.text(N_MAX, 0.3, "1 pair/s", ha="right", fontsize=9)
    a1.set_xlabel("Segments n (repeaters = n − 1)")
    a1.set_ylabel("log10 pairs per second")
    a1.set_title(f"Rate, {route} ({L:.0f} km fibre)")
    a1.legend(loc="lower right", frameon=False)
    for Fs, col, mk, ls in ((0.99, GREEN, "s", "-"), (0.95, VERM, "^", "--")):
        a2.plot(ns, [e2e_fidelity(Fs, n) for n in ns], marker=mk, ls=ls, color=col, ms=4,
                label=f"per-segment F = {Fs}")
    a2.axhline(F_KEY, color=BLACK, ls="--", lw=1.2)
    a2.text(N_MAX, F_KEY + 0.012, "key threshold 0.835", ha="right", fontsize=9)
    a2.axhline(F_CHSH, color=ORANGE, ls="-.", lw=1.5)
    a2.text(14, F_CHSH - 0.045, "CHSH > 2 above 0.7803", ha="center", fontsize=9, bbox=dict(fc="white", ec="none", pad=1))
    a2.set_xlabel("Segments n (repeaters = n − 1)")
    a2.set_ylabel("End-to-end fidelity")
    a2.set_ylim(0.2, 1.02)
    a2.set_title("Fidelity falls as segments are added")
    a2.legend(loc="lower left", frameon=False)
    fig.text(0.5, 0.005, FOOTER, ha="center", fontsize=8, color="#444444")
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT, dpi=150)
    plt.close(fig)


def main() -> None:
    print(f"Assumptions: source {SOURCE_RATE:.0e} attempts/s, ideal memories, deterministic swaps, "
          "fibre = great circle x 1.3, 0.2 dB/km, no purification, key = asymptotic Shor-Preskill x 1/2.\n")
    print(build_tables())
    print()
    print(build_sweep())
    make_figure()
    print(f"\nFigure: {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
