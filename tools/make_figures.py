"""Generate the README figures from the recorded runs in data/recorded/.

Usage (repo root):  uv run python tools/make_figures.py
Writes PNGs to docs/img/. Only the recorded JSON files and the closed-form formulas
documented in ui/leak.js / quantum/qkd.py are used; nothing is re-simulated.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib.lines import Line2D  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REC = ROOT / "data" / "recorded"
OUT = ROOT / "docs" / "img"
SIM_FILE = "basic_simulator_full.json"
QPU_FILE = "ionq_qpu_link.json"

# Okabe-Ito colour-blind safe palette
BLUE, VERM, GREEN, ORANGE, SKY, PINK, YEL, BLACK = (
    "#0072B2", "#D55E00", "#009E73", "#E69F00", "#56B4E9", "#CC79A7", "#F0E442", "#000000")

plt.rcParams.update({
    "font.size": 10.5, "axes.titlesize": 11.5, "axes.titleweight": "bold",
    "axes.spines.top": False, "axes.spines.right": False,
    "figure.facecolor": "white", "axes.facecolor": "white", "savefig.facecolor": "white",
    "axes.grid": True, "grid.color": "#dddddd", "grid.linewidth": 0.6, "axes.axisbelow": True,
})

# (level, metric) pairs the figures rely on; the test checks they exist.
REQUIRED_METRICS: dict[str, list[tuple[str, str]]] = {
    SIM_FILE: [
        ("link", "fidelity"), ("teleport", "fidelity"),
        ("noise", "fidelity@0.95"), ("noise", "fidelity@0.8"), ("noise", "fidelity@0.6"),
        ("swap", "fidelity"),
        ("purify", "fidelity_input"), ("purify", "fidelity_fixed"), ("purify", "fidelity_adaptive"),
        ("purify", "raw_pairs_fixed"), ("purify", "raw_pairs_adaptive"),
        ("purify", "p_s_fixed"), ("purify", "p_s_adaptive"),
        ("qkd", "qber_X"), ("qkd", "qber_Z"), ("qkd", "chsh_standard"), ("qkd", "chsh_smart"),
        ("rescue", "fidelity_direct"), ("rescue", "fidelity_reroute"), ("rescue", "fidelity_purify_fixed"),
    ],
    QPU_FILE: [("link", "fidelity")],
}


def load_recordings(rec_dir: Path = REC) -> dict[str, dict]:
    """Return {file name: parsed JSON} for the two recordings used by the figures."""
    return {name: json.loads((rec_dir / name).read_text()) for name in (SIM_FILE, QPU_FILE)}


def metric(rec: dict, level: str, key: str) -> dict:
    """Metric dict (value, ci95, theory, ...) of a level inside a recording."""
    return rec["levels"][level]["metrics"][key]


def _pt(rec: dict, level: str, key: str) -> tuple[float, float, float, float | None]:
    m = metric(rec, level, key)
    th = m.get("theory")
    return m["value"], m["ci95"][0], m["ci95"][1], th if isinstance(th, (int, float)) else None


def _footer(fig, files: list[str]) -> None:
    fig.text(0.5, 0.008, "Data: " + " + ".join(f"data/recorded/{f}" for f in files)
             + " · generated by tools/make_figures.py", ha="center", va="bottom",
             fontsize=8, color="#555555")


def _save(fig, name: str) -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / name
    fig.savefig(path, dpi=150, facecolor="white", transparent=False)
    plt.close(fig)
    return path


def _dots(ax, xs, pts, colors, markers, labels, xticklabel_size=9.5):
    """Measured dots with 95 % CI error bars (filled) and theory (open black diamonds)."""
    for x, (v, lo, hi, th), col, mk in zip(xs, pts, colors, markers):
        ax.errorbar([x], [v], yerr=[[v - lo], [hi - v]], fmt=mk, color=col, ms=7.5, capsize=4,
                    elinewidth=1.8, zorder=3)
        if th is not None:
            ax.plot([x + 0.14], [th], marker="D", mfc="white", mec=BLACK, mew=1.4, ms=8, ls="none", zorder=4)
    ax.set_xticks(list(xs))
    ax.set_xticklabels(labels, fontsize=xticklabel_size)
    ax.set_xlim(min(xs) - 0.6, max(xs) + 0.6)


def fig_results_vs_theory(rs: dict) -> Path:
    sim, qpu = rs[SIM_FILE], rs[QPU_FILE]
    shots = sim["shots"]
    fig, axs = plt.subplots(3, 3, figsize=(9.6, 9.0))
    ax = axs.ravel()
    kw = dict(fontsize=9)

    # 1 link
    p = [_pt(sim, "link", "fidelity"), _pt(qpu, "link", "fidelity")]
    _dots(ax[0], [0, 1], p, [BLUE, VERM], ["o", "s"], ["Simulator", "IonQ Forte 1\n(real QPU)"])
    ax[0].set_ylim(0.96, 1.01)
    ax[0].set_title("1. First link: Bell F")

    # 2 teleport
    p = [_pt(sim, "teleport", "fidelity")]
    _dots(ax[1], [0], p, [BLUE], ["o"], ["Teleported\nstate"])
    ax[1].axhline(2 / 3, color=VERM, ls="--", lw=1.6)
    ax[1].text(0.55, 2 / 3 + 0.012, "classical limit 2/3", color=VERM, ha="right", **kw)
    ax[1].set_ylim(0.55, 1.0)
    ax[1].set_title("2. Teleportation F")

    # 3 noise
    Fs = [0.95, 0.8, 0.6]
    p = [_pt(sim, "noise", f"fidelity@{F}") for F in Fs]
    _dots(ax[2], [0, 1, 2], p, [BLUE] * 3, ["o"] * 3, [f"F={F}" for F in Fs])
    ax[2].set_ylim(0.55, 1.0)
    ax[2].set_xlabel("configured fidelity", fontsize=9.5)
    ax[2].set_title("3. Noise (lab): F")

    # 4 swap
    f1, f2 = sim["levels"]["swap"]["params"]["F1"], sim["levels"]["swap"]["params"]["F2"]
    p = [_pt(sim, "swap", "fidelity")]
    _dots(ax[3], [0], p, [BLUE], ["o"], [f"swap of\nF1={f1}, F2={f2}"])
    ax[3].set_ylim(0.8, 0.9)
    ax[3].set_title("5. Repeater: swapped F")

    # 5 purify
    keys = ["fidelity_input", "fidelity_fixed", "fidelity_adaptive"]
    p = [_pt(sim, "purify", k) for k in keys]
    u_ad = metric(sim, "purify", "fidelity_adaptive")["u"]
    _dots(ax[4], [0, 1, 2], p, [BLUE] * 3, ["o"] * 3, ["input", "fixed\nDEJMPS", f"adaptive\nU={u_ad}"])
    ax[4].set_ylim(0.85, 1.0)
    ax[4].set_title("6. Distillation (damping)")

    # 6 QBER
    p = [_pt(sim, "qkd", "qber_Z"), _pt(sim, "qkd", "qber_X")]
    _dots(ax[5], [0, 1], p, [BLUE, BLUE], ["o", "o"], ["QBER Z", "QBER X"])
    ax[5].axhline(0.110, color=VERM, ls="--", lw=1.6)
    ax[5].text(1.55, 0.118, "key threshold 11 %", color=VERM, ha="right", **kw)
    ax[5].set_ylim(-0.02, 0.32)
    th_deg = round(np.degrees(sim["levels"]["qkd"]["params"]["theta"]))
    ax[5].set_title(f"7a. Catch the spy, θ={th_deg}°: QBER")

    # 7 CHSH
    p = [_pt(sim, "qkd", "chsh_standard"), _pt(sim, "qkd", "chsh_smart")]
    _dots(ax[6], [0, 1], p, [BLUE, BLUE], ["o", "o"], ["CHSH S\nstandard", "CHSH S\ndevice-informed"])
    ax[6].axhline(2.0, color=VERM, ls="--", lw=1.6)
    ax[6].text(1.55, 2.012, "classical bound 2", color=VERM, ha="right", **kw)
    ax[6].set_ylim(1.9, 2.4)
    ax[6].set_title(f"7b. Catch the spy, θ={th_deg}°: CHSH")

    # 8 rescue
    keys = ["fidelity_direct", "fidelity_reroute", "fidelity_purify_fixed"]
    p = [_pt(sim, "rescue", k) for k in keys]
    _dots(ax[7], [0, 1, 2], p, [BLUE] * 3, ["o"] * 3, ["direct\n(broken)", "reroute", "fixed\npurify"])
    tgt = sim["levels"]["rescue"]["params"]["target_F"]
    ax[7].axhline(tgt, color=VERM, ls="--", lw=1.6)
    ax[7].text(2.55, tgt + 0.008, f"target {tgt}", color=VERM, ha="right", **kw)
    ax[7].set_ylim(0.65, 0.96)
    ax[7].set_title("8. Save the network: link F")

    for a in (ax[0], ax[1], ax[2], ax[3], ax[4], ax[7]):
        a.set_ylabel("fidelity F", fontsize=9.5)
    ax[5].set_ylabel("error rate", fontsize=9.5)
    ax[6].set_ylabel("S (no unit)", fontsize=9.5)

    ax[8].axis("off")
    handles = [
        Line2D([], [], marker="o", color=BLUE, ls="-", ms=7.5, label="measured (95 % CI), simulator"),
        Line2D([], [], marker="s", color=VERM, ls="-", ms=7.5, label="measured (95 % CI), IonQ Forte 1 QPU"),
        Line2D([], [], marker="D", mfc="white", mec=BLACK, mew=1.4, ls="none", ms=8, label="theory"),
        Line2D([], [], color=VERM, ls="--", lw=1.6, label="classical bound / threshold / target"),
    ]
    ax[8].legend(handles=handles, loc="center", frameon=True, fontsize=9.5, title="Legend",
                 title_fontsize=10.5)
    fig.suptitle(f"Measured vs theory, all chapters  ·  backend: basic_simulator "
                 f"(+ real {qpu['backend']} for chapter 1)\n{shots} shots", 
                 fontsize=12, fontweight="bold", y=0.995)
    fig.tight_layout(rect=(0, 0.03, 1, 0.955))
    _footer(fig, [SIM_FILE, QPU_FILE])
    return _save(fig, "results_vs_theory.png")


def fig_purification(rs: dict) -> Path:
    sim = rs[SIM_FILE]
    lv = sim["levels"]["purify"]
    g = lv["params"]["noise"]["gamma"]
    items = [("Input pair\n(after damping)", "fidelity_input", None, SKY, "", None),
             ("Textbook DEJMPS\n(U=I, fixed)", "fidelity_fixed", "raw_pairs_fixed", VERM, "//", "p_s_fixed"),
             (f"Adaptive DEJMPS\n(U={metric(sim, 'purify', 'fidelity_adaptive')['u']})",
              "fidelity_adaptive", "raw_pairs_adaptive", GREEN, "xx", "p_s_adaptive")]
    fig, ax = plt.subplots(figsize=(7.6, 5.2))
    for i, (lab, key, pairs, col, hatch, ps) in enumerate(items):
        v, lo, hi, th = _pt(sim, "purify", key)
        ax.bar(i, v, width=0.55, color=col, edgecolor=BLACK, hatch=hatch, alpha=0.9, zorder=2)
        ax.errorbar([i], [v], yerr=[[v - lo], [hi - v]], color=BLACK, capsize=6, elinewidth=1.8, zorder=4)
        ax.plot([i + 0.18], [th], marker="D", mfc="white", mec=BLACK, mew=1.5, ms=9, ls="none", zorder=5)
        ax.text(i, 0.805, f"F = {v:.3f}", ha="center", va="bottom", fontsize=11, fontweight="bold",
                bbox=dict(fc="white", ec="none", pad=1.5), zorder=6)
        if pairs:
            n = metric(sim, "purify", pairs)["value"]
            p_s = metric(sim, "purify", ps)["value"]
            ax.text(i, 0.835, f"p_s = {p_s:.2f}\n{n:.2f} raw pairs / output", ha="center", va="bottom",
                    fontsize=9, bbox=dict(fc="white", ec="none", pad=1.5), zorder=6)
    fin = metric(sim, "purify", "fidelity_input")["value"]
    ax.axhline(fin, color=BLACK, ls=":", lw=1.4)
    ax.text(0.5, fin + 0.003, "input fidelity", ha="center", va="bottom", fontsize=9)
    ax.set_xticks(range(3))
    ax.set_xticklabels([i[0] for i in items], fontsize=10)
    ax.set_ylim(0.8, 1.0)
    ax.set_xlim(-0.6, 2.6)
    ax.set_ylabel("fidelity F with the Bell pair (axis starts at 0.80)")
    ax.set_title(f"Amplitude damping γ={g}: textbook DEJMPS does not purify, adaptive does\n"
                 f"(basic_simulator, {sim['shots']} shots, bars = measured with 95 % CI)",
                 fontsize=11)
    ax.legend(handles=[Line2D([], [], marker="D", mfc="white", mec=BLACK, mew=1.5, ls="none", ms=9,
                              label="theory (exact density matrix)"),
                       Line2D([], [], color=BLACK, lw=1.8, marker="_", ms=10, label="measured 95 % CI")],
              loc="upper left", fontsize=9)
    fig.tight_layout(rect=(0, 0.035, 1, 1))
    _footer(fig, [SIM_FILE])
    return _save(fig, "purification_adaptive.png")


def fig_noise_listening(rs: dict) -> Path:
    sim = rs[SIM_FILE]
    q = sim["levels"]["qkd"]
    th_deg = np.degrees(q["params"]["theta"])
    deg = np.linspace(0, 180, 721)
    c = np.cos(np.radians(deg) / 2)
    F = (1 + c) / 2
    # formulas from ui/leak.js: spy (CRY) vs environment (Werner) at the same F
    qx_spy, qz_spy, s_spy = (1 - c) / 2, 0 * c, np.sqrt(2) * (1 + c)
    q_env, s_env = 2 * (1 - F) / 3, 2 * np.sqrt(2) * (4 * F - 1) / 3

    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10.4, 5.0))
    a1.plot(deg, F, color=BLACK, lw=2.2, ls="-", label="fidelity F (same for both)")
    a1.plot(deg, qx_spy, color=VERM, lw=2.2, ls="--", label="spy: QBER X = (1−c)/2")
    a1.plot(deg, qz_spy, color=VERM, lw=2.2, ls=":", label="spy: QBER Z = 0")
    a1.plot(deg, q_env, color=BLUE, lw=2.2, ls="-.", label="environment: QBER = 2(1−F)/3 (any basis)")
    a1.axhline(0.110, color=GREEN, lw=1.4, ls=(0, (6, 3)))
    a1.text(2, 0.122, "key threshold QBER 11 %", color=GREEN, fontsize=9)
    v, lo, hi, _ = _pt(sim, "qkd", "qber_X")
    a1.errorbar([th_deg], [v], yerr=[[v - lo], [hi - v]], fmt="o", color=VERM, mec=BLACK, ms=9, capsize=5,
                elinewidth=1.8, zorder=5, label="measured QBER X, spy (95 % CI)")
    a1.set_xlabel("spy angle θ (degrees)    [c = cos(θ/2)]")
    a1.set_ylabel("fidelity / error rate")
    a1.set_xlim(0, 180)
    a1.set_ylim(-0.02, 1.02)
    a1.set_xticks(range(0, 181, 30))
    a1.set_title("Fidelity and error rates vs spy angle")
    a1.legend(fontsize=8.3, loc="center left", bbox_to_anchor=(0.0, 0.62))

    a2.plot(deg, s_spy, color=VERM, lw=2.2, ls="--", label="spy: S = √2 (1+c)")
    a2.plot(deg, s_env, color=BLUE, lw=2.2, ls="-.", label="environment: S = 2√2 (4F−1)/3")
    a2.axhline(2.0, color=BLACK, lw=1.6, ls="-")
    a2.text(2, 2.04, "classical bound S = 2", fontsize=9)
    a2.axhline(2 * np.sqrt(2), color="#777777", lw=1.0, ls=":")
    a2.text(178, 2 * np.sqrt(2) + 0.04, "Tsirelson 2√2", fontsize=8.5, ha="right", color="#555555")
    th_spy = np.degrees(2 * np.arccos(np.sqrt(2) - 1))  # sqrt2 (1+c) = 2
    F_env = (1 + 3 / np.sqrt(2)) / 4  # 2 sqrt2 (4F-1)/3 = 2  (F = 0.7803)
    c_env = 2 * F_env - 1
    th_env = np.degrees(2 * np.arccos(c_env))
    for t_, col in ((th_spy, VERM), (th_env, BLUE)):
        a2.axvline(t_, color=col, lw=1.0, ls=":")
        a2.text(t_ + 1.5, 0.05, f"{t_:.1f}°", color=col, fontsize=8.5, rotation=90, va="bottom")
    v, lo, hi, _ = _pt(sim, "qkd", "chsh_standard")
    a2.errorbar([th_deg], [v], yerr=[[v - lo], [hi - v]], fmt="o", color=VERM, mec=BLACK, ms=9, capsize=5,
                elinewidth=1.8, zorder=5, label="measured S standard, spy (95 % CI)")
    a2.set_xlabel("spy angle θ (degrees)    [c = cos(θ/2)]")
    a2.set_ylabel("CHSH S (no unit)")
    a2.set_xlim(0, 180)
    a2.set_ylim(0, 3.0)
    a2.set_xticks(range(0, 181, 30))
    a2.set_title("CHSH vs spy angle: entanglement is the budget")
    a2.legend(fontsize=8.3, loc="lower left", bbox_to_anchor=(0.0, 0.1))
    fig.suptitle("Noise is someone listening: the spy and the environment drain the same fidelity\n"
                 f"(measured: basic_simulator, {sim['shots']} shots)", fontsize=11.5, fontweight="bold", y=0.995)
    fig.tight_layout(rect=(0, 0.035, 1, 0.93))
    _footer(fig, [SIM_FILE])
    return _save(fig, "noise_is_someone_listening.png")


def main() -> int:
    rs = load_recordings()
    for fn in (fig_results_vs_theory, fig_purification, fig_noise_listening):
        path = fn(rs)
        print(f"{path.relative_to(ROOT)}  {path.stat().st_size / 1024:.0f} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
